-- 合规性没有、判成了什么。形状与理由见 src/lib/impact-review.ts。
--
-- 为什么需要它（不是"顺手加个日志"）：判读是全站唯一一段**推断**，而用户 2026-10-04 拍板
-- 「带门扩」——扩到行业专业档，但渲染前必须由与被审读内容**不同来源**的模型判一遍
-- （通过 / 改文本 / 剔除）。没有这一列，就没有任何东西能回答"这条判读还被审读过吗"，
-- 也就无法在生成侧重跑之后让旧结论失效。
--
-- 为什么是独立的列而不是塞进 ai_summary_json：那一列是**渲染契约**，往里加键就要同时改读侧，
