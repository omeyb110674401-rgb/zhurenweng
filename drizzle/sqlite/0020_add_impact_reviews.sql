-- 这一列还必须是**可抛弃的**：审读不覆盖生成侧产物，重跑即按内容指纹失效。
--
-- 可空、不回填：NULL = 本列上线前的存量、人工复核手工录入的摘要、或审读还没跑/没跑成。
-- （判读本身**不迁表**：逐条生命周期由这一列按内容指纹承担，见 91 号文档第八节第 19 条。）
